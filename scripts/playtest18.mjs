import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 420, height: 800 }, hasTouch: true, isMobile: true });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => window.__game);
await page.screenshot({ path: 'shots/iter20_phone_title.png' });
await page.click('#t-daily');
await page.evaluate(() => document.getElementById('help').classList.add('hidden'));
await page.waitForTimeout(300);
const boxes = await page.evaluate(() => Object.fromEntries(['topbar', 'toolbar', 'tasks', 'log', 'minimap'].map((id) => { const e = document.getElementById(id); const r = e.getBoundingClientRect(); return [id, [Math.round(r.left), Math.round(r.top), Math.round(r.right), Math.round(r.bottom)]]; })));
console.log('phone boxes', JSON.stringify(boxes));
const ov = (a, b) => a[0] < b[2] && b[0] < a[2] && a[1] < b[3] && b[1] < a[3];
console.log('toolbar/log overlap:', ov(boxes.toolbar, boxes.log), 'minimap/log overlap:', ov(boxes.minimap, boxes.log), 'page width ok:', await page.evaluate(() => document.documentElement.scrollWidth <= 420));
await page.screenshot({ path: 'shots/iter20_phone_game.png' });
console.log('aria labels:', await page.evaluate(() => document.querySelectorAll('button[aria-label]').length), 'score banner:', await page.evaluate(() => document.querySelector('#tasks .score')?.textContent?.slice(0, 60)));
console.log('errors', errors);
await browser.close();
