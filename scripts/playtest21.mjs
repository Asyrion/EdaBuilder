import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1400, height: 800 } });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => window.__game);
await page.evaluate(() => { window.__game.newGame(41, 'Weave'); document.getElementById('help').classList.add('hidden'); document.getElementById('title').classList.add('hidden'); });
console.log(await page.evaluate(() => { const s = window.__game.state; return 'aspects: ' + s.nodes.map((n) => n.aspect).join(','); }));
await page.evaluate(() => { const g = window.__game, s = g.state; g.selectedNode = 0; g.paused = true; g.renderer.camera.centerOnTile(s.founding.x, s.founding.y); g.renderer.camera.setZoom(3); g.ui.refresh(); });
await page.waitForTimeout(300);
console.log('node panel:', await page.evaluate(() => document.querySelector('#info')?.innerText.replace(/\n/g, ' | ').slice(0, 260)));
await page.screenshot({ path: 'shots/iter23_node.png' });
// Marvels tab
await page.evaluate(() => { const s = window.__game.state; s.milestone = 6; s.materials.scale = 12; s.materials.wyrmfire = 9; window.__game.ui.refreshItems(); });
await page.click('#toolbar .tabs button:nth-child(7)');
await page.waitForTimeout(200);
console.log('marvels tab:', await page.evaluate(() => Array.from(document.querySelectorAll('#toolbar .items button')).map((b) => b.textContent.trim().replace(/\s+/g, ' ')).join(' | ')));
await page.screenshot({ path: 'shots/iter23_marvels.png' });
await page.click('#btn-wyrms'); await page.waitForTimeout(200);
console.log('wyrms panel pressure line:', await page.evaluate(() => Array.from(document.querySelectorAll('#wyrms p')).map((p) => p.textContent).find((t) => t.includes('Gloam is'))));
console.log('errors', errors);
await browser.close();
