// Iteration 47, services with staff and stakes: a hearth's why-lines and level-up needs, a short-handed Watch House, a Scale Ward's re-plate button.
import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1400, height: 800 } });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => window.__game);
await page.fill('#t-seed', '42'); await page.click('#t-new'); await page.waitForTimeout(300);
await page.evaluate(() => { document.getElementById('help').classList.add('hidden'); window.__game.paused = true; });
const info = await page.evaluate(() => { const g = window.__game, s = g.state, w = window.__wardlight, f = s.founding; s.milestone = 6; s.treasury = 90000; s.sectors.fill(1);
  for (let y = f.y - 10; y <= f.y + 12; y++) for (let x = f.x - 18; x <= f.x + 18; x++) { const i = y * s.w + x; if (s.terrain[i] !== 7) s.terrain[i] = 3; }
  w.actions.buildRoad(s, 1, w.actions.roadPath(f.x - 16, f.y + 2, f.x + 16, f.y + 2, false));
  const h = w.place(s, 'hearth', f.x - 2, f.y + 1, 2);
  const wh = w.place(s, 'watchhouse', f.x + 4, f.y + 3);
  const sw = w.place(s, 'scaleward', f.x - 8, f.y - 3);
  w.place(s, 'shrine', f.x + 2, f.y - 2);
  for (const b of s.buildings) if (b && b.state === 'building') { b.state = 'ok'; b.work = 0; }
  h.residents = 6; wh.workers = 4; sw.plate = 0.6; s.materials.scale = 5; s.unrest = 0.15;
  w.recomputeAll(s); g.renderer.invalidateAll();
  g.select(h); g.ui.refresh();
  const t1 = document.body.textContent;
  const why = (t1.match(/\+\d+ [a-z ]+/g) ?? []).length, needs = /Level 3 needs/.test(t1), unrestTerm = /-\d+ unrest/.test(t1);
  g.select(wh); g.ui.refresh();
  const t2 = document.body.textContent;
  const crew = /Crew\s*4 \/ 10/.test(t2), short = /Short-handed/.test(t2);
  g.select(sw); g.ui.refresh();
  const t3 = document.body.textContent;
  const plating = /Plating\s*60 %/.test(t3), burns = /Burns\s*7 grey tiles/.test(t3);
  const btn = [...document.querySelectorAll('button')].find((b) => /Re-plate/.test(b.textContent));
  const enabled = btn && !btn.disabled;
  if (btn) btn.click();
  const after = sw.plate, scale = s.materials.scale;
  g.renderer.camera.centerOnTile(f.x, f.y); g.renderer.camera.setZoom(2);
  g.select(h); g.ui.refresh();
  return { why, needs, unrestTerm, crew, short, plating, burns, enabled, after, scale };
});
console.log('panels:', JSON.stringify(info));
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/iter47_stakes.png' });
const pass = info.why >= 2 && info.needs && info.unrestTerm && info.crew && info.short && info.plating && info.burns && info.enabled && info.after === 1 && info.scale === 3 && errors.length === 0;
console.log(pass ? 'PASS' : 'FAIL', 'errors', errors);
await browser.close();
