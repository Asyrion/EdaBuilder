import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1400, height: 800 } });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => window.__game);
await page.evaluate(() => { window.__game.newGame(41, 'DevMenu'); document.getElementById('help').classList.add('hidden'); document.getElementById('title').classList.add('hidden'); });
await page.keyboard.press('`'); await page.waitForTimeout(300);
console.log('open:', await page.evaluate(() => !document.getElementById('dev').classList.contains('hidden')));
console.log('groups:', await page.evaluate(() => Array.from(document.querySelectorAll('#dev h3')).map((h) => h.textContent).join(' | ')));
console.log('buttons:', await page.evaluate(() => document.querySelectorAll('#dev button[data-id]').length));
await page.screenshot({ path: 'shots/iter28_dev.png' });
await page.click('#dev button[data-id="crowns"]'); await page.waitForTimeout(150);
await page.selectOption('#dev select[data-arg="egg"]', 'ember');
await page.click('#dev button[data-id="egg"]'); await page.waitForTimeout(150);
await page.click('#dev button[data-id="hounds"]'); await page.waitForTimeout(150);
await page.click('#dev button[data-id="day"]'); await page.waitForTimeout(300);
console.log('status:', await page.evaluate(() => document.querySelector('#dev .devstatus')?.textContent.slice(0, 200)));
console.log('last:', await page.evaluate(() => document.querySelector('#dev .good')?.textContent));
console.log('state:', await page.evaluate(() => { const s = window.__game.state; return `day=${s.day} treasury=${Math.round(s.treasury)} hounds=${s.agents.filter((a) => a.species === 'hound').length} devUses=${s.stats.devUses} paused=${window.__game.paused}`; }));
await page.click('#dev-close'); await page.waitForTimeout(100);
console.log('closed:', await page.evaluate(() => document.getElementById('dev').classList.contains('hidden')));
// menu entry
await page.click('#btn-menu'); await page.waitForTimeout(100);
console.log('menu entry:', await page.evaluate(() => document.getElementById('m-dev')?.textContent));
console.log('errors', errors);
await browser.close();
