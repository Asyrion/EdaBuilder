import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1500, height: 850 } });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => window.__game);
await page.screenshot({ path: 'shots/iter17_title.png' });
await page.click('#title .scenarios button[data-sc="inherited"]');
await page.click('#t-new');
await page.evaluate(() => { document.getElementById('help').classList.add('hidden'); });
await page.waitForTimeout(500);
console.log(await page.evaluate(() => { const s = window.__game.state; return `scenario=${s.scenario} treasury=${s.treasury} ruins=${s.buildings.filter((b) => b && b.state === 'ruin').length} restless=${s.agents.filter((a) => a.kind === 2).length} first quest=${document.querySelector('#tasks .q.now .t')?.textContent}`; }));
await page.evaluate(() => { const g = window.__game, s = g.state, A = window.__wardlight.actions; const f = s.founding; A.paintDistrict(s, 1, f.x - 8, f.y - 6, f.x + 8, f.y + 8); g.view.overlay = 'district'; g.ui.refreshViews(); g.paused = true; g.renderer.camera.centerOnTile(f.x, f.y + 2); g.renderer.camera.setZoom(2); });
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/iter17_district.png' });
await page.click('#tasks .done'); await page.waitForTimeout(200);
console.log('done page:', await page.evaluate(() => document.querySelector('#tasks .list').innerText.replace(/\n/g, ' | ').slice(0, 160)));
await page.screenshot({ path: 'shots/iter17_done.png' });
console.log('errors', errors);
await browser.close();
