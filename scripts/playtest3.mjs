import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1500, height: 850 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => window.__game);
await page.evaluate(() => { window.__game.newGame(42, 'Thornwick'); document.getElementById('help').classList.add('hidden'); document.getElementById('title').classList.add('hidden'); });
await page.evaluate(() => { const g = window.__game, W = window.__wardlight; const bot = new W.Bot(g.state); for (let d = 0; d < 45; d++) { for (let i = 0; i < 900; i++) W.tick(g.state); bot.step(); } W.recomputeAll(g.state); g.renderer.invalidateAll(); g.paused = true; });
const f = await page.evaluate(() => window.__game.state.founding);
const tileToScreen = async (x, y) => page.evaluate(([x, y]) => { const cam = window.__game.renderer.camera; const wx = (x - y) * 16, wy = (x + y) * 8 + 8; return [(wx - cam.left) * cam.zoom, (wy - cam.top) * cam.zoom]; }, [x, y]);
await page.click('#toolbar .tabs button:has-text("Districts")');
await page.click('#toolbar .items button:has-text("Stillward")');
let [ax, ay] = await tileToScreen(f.x - 8, f.y - 2);
let [bx, by] = await tileToScreen(f.x + 4, f.y + 6);
await page.mouse.move(ax, ay); await page.mouse.down(); await page.mouse.move(bx, by, { steps: 6 }); await page.mouse.up();
console.log('district tiles:', await page.evaluate(() => window.__game.state.district.reduce((a, b) => a + (b ? 1 : 0), 0)));
await page.keyboard.press('i');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/districts.png' });
await page.keyboard.press('Escape');
await page.click('#btn-edicts');
await page.waitForTimeout(200);
await page.selectOption('#e-scope', '2');
await page.waitForTimeout(200);
await page.click('#edicts input[data-key="herbgardens"]');
await page.waitForTimeout(200);
console.log('district edict:', await page.evaluate(() => window.__game.state.districtEdicts['2:herbgardens']));
await page.screenshot({ path: 'shots/edicts_district.png' });
await page.click('#e-close');
await page.keyboard.press('o');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/goods_overlay.png' });
await page.keyboard.press('Escape');
console.log('mines:', await page.evaluate(() => window.__game.state.buildings.filter((b) => b && b.kind === 'mine').length), 'arcane:', await page.evaluate(() => window.__game.state.buildings.filter((b) => b && b.kind === 'arcane').length), 'artifacts:', await page.evaluate(() => window.__game.state.artifactsSold));
await page.click('#btn-menu'); await page.click('#m-cb'); await page.click('#m-scale'); await page.waitForTimeout(200);
console.log('settings:', await page.evaluate(() => JSON.stringify(window.__game.settings)));
await page.click('#m-close');
await page.keyboard.press('3'); await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/cb_landvalue.png' });
console.log('errors', errors);
await browser.close();
